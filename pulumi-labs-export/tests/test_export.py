class ExportBase(helpers.TempDirMixin, unittest.TestCase):
    slug = "demo"

    def setUp(self):
        super().setUp()
        self.mono = helpers.build_monorepo(self.tmp, self.slug)
        self.out = helpers.build_out(self.tmp)
        self.n = names.derive(self.slug)

    def do_export(self, out=None, **kw):
        return export.export(self.mono, self.slug, out or self.out, skill_commit=kw.pop("skill_commit", None), **kw)

    def mutate(self, rel, fn):
        path = os.path.join(self.mono, "lib/providers/%s/%s" % (self.slug, rel))
        with open(path, encoding="utf-8") as f:
            helpers.write(self.mono, "lib/providers/%s/%s" % (self.slug, rel), fn(f.read()))
        helpers.commit_all(self.mono, "mutate " + rel)

    def read(self, rel, root=None):
        with open(os.path.join(root or self.out, rel), encoding="utf-8") as f:
            return f.read()

    def assertRefused(self, pattern):
        with self.assertRaises(export.ExportError) as cm:
            self.do_export()
        self.assertRegex(str(cm.exception), pattern)
        return str(cm.exception)


class TransformTest(ExportBase):
    def test_module_and_imports_rewritten(self):
        self.do_export()
        self.assertTrue(self.read("go.mod").startswith("module github.com/pulumi-labs/pulumi-demo\n"))
        self.assertIn("require github.com/pulumi/pulumi-go-provider v1.3.1", self.read("go.mod"))
        main = self.read("provider/cmd/pulumi-resource-demo/main.go")
        self.assertIn('"github.com/pulumi-labs/pulumi-demo/provider/pkg/provider"', main)
        self.assertNotIn("pulumi/autoregistry", main)
        self.assertIn("pulumi-labs/pulumi-demo/provider/pkg/version", self.read("provider/pkg/provider/provider_test.go"))
        self.assertIn("pulumi-labs/pulumi-demo/provider/pkg/version", self.read("examples/demo-go/main.go"))
        self.assertEqual(self.read("go.sum"), "github.com/pulumi/pulumi-go-provider v1.3.1 h1:abc=\n")

    def test_copied_and_generated_files(self):
        self.do_export()
        for rel in ("README.md", "CHANGELOG.md", "docs/_index.md", "docs/installation-configuration.md",
                    "templates/demo-go/Pulumi.yaml", "examples/demo-go/go.mod", "examples/demo-go/main.go"):
            self.assertTrue(os.path.isfile(os.path.join(self.out, rel)), rel)
        claude = self.read("CLAUDE.md")
        self.assertTrue(claude.startswith("<!-- Generated by pulumi-labs-export"))
        self.assertTrue(claude.endswith("# Demo dev guide\n\nBuild with make.\n"))
        self.assertNotIn("pulumi/autoregistry", claude)
        # archetype files come from render.py
        self.assertIn("pulumi-labs/pulumi-demo/provider/pkg/version.Version", self.read("Makefile"))
        self.assertTrue(os.path.isfile(os.path.join(self.out, ".github/workflows/release.yml")))

    def test_executable_bit_kept(self):
        self.do_export()
        self.assertTrue(os.stat(os.path.join(self.out, "examples/run.sh")).st_mode & 0o111)
        self.assertFalse(os.stat(os.path.join(self.out, "README.md")).st_mode & 0o111)

    def test_never_copied(self):
        self.do_export()
        files = helpers.tree(self.out)
        self.assertNotIn("version.txt", files)
        self.assertNotIn("provider/go.mod", files)
        self.assertNotIn("provider/go.sum", files)
        self.assertFalse([f for f in files if f.startswith("skills/")])
        self.assertNotIn("MONOREPO MAKEFILE MARKER", self.read("Makefile"))
        self.assertNotIn("MONOREPO GITIGNORE MARKER", self.read(".gitignore"))
        self.assertNotIn("carved-providers.json", files)
        self.assertNotIn("monorepo root", "".join(v[0].decode("utf-8", "replace") for v in files.values()))

    def test_export_reads_the_commit_not_the_worktree(self):
        # a clean checkout is required, so stale ignored output cannot leak either; ignored files are not in git archive
        helpers.write(self.mono, ".gitignore", "lib/providers/demo/provider/pkg/junk.go\n")
        helpers.commit_all(self.mono, "ignore")
        helpers.write(self.mono, "lib/providers/demo/provider/pkg/junk.go", "package junk\n")
        self.do_export()
        self.assertNotIn("provider/pkg/junk.go", helpers.tree(self.out))


class OptionsFileTest(ExportBase):
    def test_content(self):
        opts = self.do_export(skill_commit="abc123")
        sha = helpers.git(self.mono, "rev-parse", "HEAD").strip()
        rec = json.loads(self.read(render.OPTIONS_FILE))
        self.assertEqual(rec, opts)
        manifest = render.load_manifest()
        self.assertEqual(rec["provider"], "demo")
        self.assertEqual(rec["display_name"], "Demo")
        self.assertEqual(rec["archetype_sha"], manifest["archetype_sha"])
        self.assertEqual(rec["archetype_repo"], manifest["archetype_repo"])
        self.assertEqual(rec["source_repo"], "pulumi/autoregistry")
        self.assertEqual(rec["source_sha"], sha)
        self.assertEqual(rec["source_version"], "0.1.0")
        self.assertEqual(rec["skill_commit"], "abc123")
        self.assertEqual(rec["exclude_platforms"], [])

    def test_exclude_platforms_recorded_and_reused(self):
        self.do_export(excludes=[("windows/amd64", "does not build")])
        self.assertEqual(json.loads(self.read(render.OPTIONS_FILE))["exclude_platforms"][0]["platform"], "windows/amd64")
        self.do_export()  # no flags: recorded options persist across syncs
        self.assertEqual(json.loads(self.read(render.OPTIONS_FILE))["exclude_platforms"][0]["reason"], "does not build")
        self.assertIn("windows/amd64 is off the matrix", self.read(".github/workflows/test.yml"))

    def test_render_py_keeps_the_export_record(self):
        self.do_export()
        before = json.loads(self.read(render.OPTIONS_FILE))
        self.assertEqual(helpers.quiet(render.main, ["--repo-dir", self.out]), 0)
        self.assertEqual(json.loads(self.read(render.OPTIONS_FILE)), before)

    def test_display_name_flag_beats_source(self):
        self.do_export(display_name="Demo Thing")
        self.assertEqual(json.loads(self.read(render.OPTIONS_FILE))["display_name"], "Demo Thing")

    def test_version_must_be_zero_x(self):
        self.mutate("version.txt", lambda s: "1.0.0\n")
        self.assertRefused(r"0\.x\.y")


class DeterminismTest(ExportBase):
    def test_two_runs_are_identical(self):
        out2 = helpers.build_out(self.tmp, "mirror2")
        self.do_export()
        self.do_export(out=out2)
        self.assertEqual(helpers.tree(self.out), helpers.tree(out2))

    def test_rerun_into_same_dir_is_identical(self):
        self.do_export()
        first = helpers.tree(self.out)
        self.do_export()
        self.assertEqual(helpers.tree(self.out), first)

    def test_umask_does_not_matter(self):
        old = os.umask(0o077)
        try:
            out2 = helpers.build_out(self.tmp, "mirror2")
            self.do_export(out=out2)
        finally:
            os.umask(old)
        self.do_export()
        self.assertEqual(helpers.tree(self.out), helpers.tree(out2))
        self.assertEqual(os.stat(os.path.join(out2, "README.md")).st_mode & 0o777, 0o644)


class OverwriteTest(ExportBase):
    def test_leftovers_removed_and_git_kept(self):
        self.do_export()
        helpers.write(self.out, "stale.txt", "x")
        helpers.write(self.out, "deep/er/stale.txt", "x")
        helpers.write(self.out, "provider/pkg/provider/hand_edit.go", "package provider\n")
        helpers.write(self.out, "README.md", "hand edited\n")
        self.do_export()
        files = helpers.tree(self.out)
        for rel in ("stale.txt", "deep/er/stale.txt", "provider/pkg/provider/hand_edit.go"):
            self.assertNotIn(rel, files)
        self.assertIn("Demo", self.read("README.md"))
        self.assertTrue(os.path.isdir(os.path.join(self.out, ".git")))
        self.assertEqual(helpers.git(self.out, "rev-parse", "--git-dir").strip(), ".git")

    def test_failed_export_leaves_the_mirror_untouched(self):
        self.do_export()
        before = helpers.tree(self.out)
        self.mutate("docs/_index.md", lambda s: s)  # no-op commit
        os.remove(os.path.join(self.mono, "lib/providers/demo/docs/_index.md"))
        helpers.commit_all(self.mono, "rm docs")
        self.assertRefused("_index.md")
        self.assertEqual(helpers.tree(self.out), before)

    def test_out_without_git_is_refused(self):
        bare = os.path.join(self.tmp, "plain")
        os.makedirs(bare)
        helpers.write(bare, "precious.txt", "x")
        with self.assertRaises(export.ExportError):
            export.export(self.mono, self.slug, bare, skill_commit=None)
        self.assertTrue(os.path.exists(os.path.join(bare, "precious.txt")))

    def test_out_inside_monorepo_is_refused(self):
        inner = helpers.build_out(self.mono, "inner")
        with self.assertRaises(export.ExportError):
            export.export(self.mono, self.slug, inner, skill_commit=None)


class RefusalTest(ExportBase):
    def test_relative_replace(self):
        self.mutate("provider/go.mod", lambda s: s + "\nreplace github.com/x/y => ../../y\n")
        msg = self.assertRefused(r"relative replace")
        self.assertIn("github.com/x/y => ../../y", msg)
        self.assertEqual(helpers.tree(self.out), {})

    def test_replace_block_with_relative_path(self):
        self.mutate("provider/go.mod", lambda s: s + "\nreplace (\n\tgithub.com/x/y => ./y\n)\n")
        self.assertRefused(r"relative replace")

    def test_versioned_replace_is_allowed(self):
        self.mutate("provider/go.mod", lambda s: s + "\nreplace github.com/x/y => github.com/z/y v1.0.0\n")
        self.do_export()
        self.assertIn("replace github.com/x/y => github.com/z/y v1.0.0", self.read("go.mod"))

    def test_missing_docs(self):
        for i, rel in enumerate(("docs/_index.md", "docs/installation-configuration.md")):
            root = os.path.join(self.tmp, "case%d" % i)
            os.makedirs(root)
            mono = helpers.build_monorepo(root)
            os.remove(os.path.join(mono, "lib/providers/demo", rel))
            helpers.commit_all(mono, "rm")
            with self.assertRaises(export.ExportError) as cm:
                export.export(mono, "demo", helpers.build_out(root), skill_commit=None)
            msg = str(cm.exception)
            self.assertIn(rel, msg)
            self.assertIn("identity-switch PR", msg)
            self.assertIn("archetype", msg)

    def test_not_listed(self):
        helpers.write(self.mono, "carved-providers.json", "[]\n")
        helpers.commit_all(self.mono, "unlist")
        self.assertRefused(r"does not list provider 'demo'")

    def test_not_mirror_mode(self):
        path = os.path.join(self.mono, "carved-providers.json")
        with open(path) as f:
            entries = json.load(f)
        entries[0]["mode"] = "carve"
        helpers.write(self.mono, "carved-providers.json", json.dumps(entries))
        helpers.commit_all(self.mono, "mode")
        self.assertRefused(r"only \"mirror\"")

    def test_wrong_repo_in_entry(self):
        path = os.path.join(self.mono, "carved-providers.json")
        with open(path) as f:
            entries = json.load(f)
        entries[0]["repo"] = "pulumi-labs/pulumi-other"
        helpers.write(self.mono, "carved-providers.json", json.dumps(entries))
        helpers.commit_all(self.mono, "repo")
        self.assertRefused(r"repo 'pulumi-labs/pulumi-other'")

    def test_dirty_monorepo(self):
        helpers.write(self.mono, "lib/providers/demo/README.md", "dirty\n")
        self.assertRefused(r"not clean")
        os.remove(os.path.join(self.mono, "lib/providers/demo/README.md"))
        helpers.git(self.mono, "checkout", "--", ".")
        helpers.write(self.mono, "untracked.txt", "x")
        self.assertRefused(r"not clean")

    def test_old_identity_in_builder(self):
        self.mutate("provider/pkg/provider/provider.go", lambda s: s.replace('WithPublisher("Pulumi Labs")', 'WithPublisher("Pulumi")'))
        msg = self.assertRefused(r"identity-switch PR")
        self.assertIn('WithPublisher("Pulumi")', msg)
        self.assertIn("provider/pkg/provider/provider.go:", msg)

    def test_old_namespace_in_docs_or_examples(self):
        self.mutate("README.md", lambda s: s + "\nnpm i @pulumi/demo\n")
        msg = self.assertRefused(r"still has pulumi/ identity values")
        self.assertIn("README.md:", msg)

    def test_module_not_the_monorepo_one(self):
        self.mutate("provider/go.mod", lambda s: s.replace("github.com/pulumi/autoregistry/lib/providers/demo/provider", "example.com/other"))
        self.assertRefused(r"declares module example\.com/other")

    def test_missing_skills_md(self):
        os.remove(os.path.join(self.mono, "lib/providers/demo/skills/SKILLS.md"))
        helpers.commit_all(self.mono, "rm")
        self.assertRefused(r"SKILLS\.md")

    def test_cli_exit_codes(self):
        base = ["--monorepo", self.mono, "--provider", "demo", "--out", self.out]
        self.assertEqual(helpers.quiet(export.main, base), 0)
        self.assertEqual(helpers.quiet(export.main, ["--monorepo", self.mono, "--provider", "Bad_Slug", "--out", self.out]), 1)


class DriftTest(ExportBase):
    def mirror(self):
        self.do_export()
        helpers.commit_all(self.out, "Export")

    def drift(self):
        return export.drift(self.out, self.mono)

    def test_clean_mirror_has_no_drift(self):
        self.mirror()
        self.assertEqual(self.drift(), [])

    def test_hand_edit_listed(self):
        self.mirror()
        helpers.write(self.out, "provider/pkg/provider/provider.go", self.read("provider/pkg/provider/provider.go") + "// hand edit\n")
        self.assertEqual([d.split(":")[0] for d in self.drift()], ["provider/pkg/provider/provider.go"])

    def test_every_differing_path_listed(self):
        self.mirror()
        helpers.write(self.out, "README.md", "changed\n")
        helpers.write(self.out, "extra.txt", "new\n")
        os.remove(os.path.join(self.out, "docs/_index.md"))
        helpers.write(self.out, ".github/workflows/test.yml", "name: hacked\n")
        got = {d.split(":")[0]: d for d in self.drift()}
        self.assertEqual(sorted(got), [".github/workflows/test.yml", "README.md", "docs/_index.md", "extra.txt"])
        self.assertIn("missing", got["docs/_index.md"])
        self.assertIn("unexpected", got["extra.txt"])

    def test_exec_bit_change_is_drift(self):
        self.mirror()
        os.chmod(os.path.join(self.out, "examples/run.sh"), 0o644)
        self.assertEqual([d.split(":")[0] for d in self.drift()], ["examples/run.sh"])

    def test_sdk_and_schema_are_ignored(self):
        self.mirror()
        helpers.write(self.out, self.n["schema_path"], "{}\n")
        helpers.write(self.out, "sdk/go/demo/x.go", "package demo\n")
        helpers.write(self.out, "sdk/nodejs/package.json", "{}\n")
        self.assertEqual(self.drift(), [])

    def test_gitignored_build_output_is_ignored(self):
        self.mirror()
        helpers.write(self.out, "bin/pulumi-resource-demo", "binary")
        self.assertEqual(self.drift(), [])

    def test_uses_the_recorded_sha_not_monorepo_head(self):
        self.mirror()
        self.mutate("README.md", lambda s: s + "newer monorepo change\n")
        self.assertEqual(self.drift(), [])  # the mirror is stale, not hand edited
        # a fresh export at the new HEAD then differs only because the source moved on
        self.do_export()
        self.assertIn("newer monorepo change", self.read("README.md"))

    def test_missing_commit_is_a_clear_error(self):
        self.mirror()
        rec = json.loads(self.read(render.OPTIONS_FILE))
        rec["source_sha"] = "0" * 40
        helpers.write(self.out, render.OPTIONS_FILE, json.dumps(rec))
        with self.assertRaises(export.ExportError) as cm:
            self.drift()
        self.assertIn("never uses the network", str(cm.exception))

    def test_not_an_export(self):
        helpers.write(self.out, render.OPTIONS_FILE, json.dumps({"provider": "demo"}))
        with self.assertRaises(export.ExportError):
            self.drift()

    def test_check_py_reports_drift(self):
        self.mirror()
        def drift_lines():
            return [f for f in check.check_repo(self.out, against_source=self.mono) if f.startswith("DRIFT")]
        self.assertEqual(drift_lines(), [])
        helpers.write(self.out, "CONTRIBUTING.md", "hand edit\n")
        lines = drift_lines()
        self.assertTrue(any(l.startswith("DRIFT CONTRIBUTING.md") for l in lines), lines)
        self.assertTrue(any("Fixes land in the monorepo first" in l for l in lines))
        # without the flag nothing is compared
        self.assertFalse([f for f in check.check_repo(self.out) if f.startswith("DRIFT")])

    def test_check_py_main_flag_and_options_file_not_scanned_for_namespace(self):
        self.mirror()
        rec = self.read(render.OPTIONS_FILE)
        self.assertIn("pulumi/autoregistry", rec)  # source_repo is recorded...
        fails = check.check_repo(self.out)
        self.assertFalse([f for f in fails if "NAMESPACE" in f], fails)  # ...and is not a namespace hit
        self.assertEqual(helpers.quiet(check.main, ["--repo", self.out, "--against-source", self.mono]), 1)  # no schema/sdk yet


