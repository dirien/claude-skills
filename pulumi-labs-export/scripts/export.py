class ExportError(Exception):
    """Raised for any condition the operator must fix; the message is actionable."""


def _git_bytes(repo, *args):
    p = subprocess.run(["git", "-C", repo] + list(args), capture_output=True, check=False)
    if p.returncode != 0:
        raise ExportError("git %s failed in %s: %s" % (" ".join(args[:2]), repo, p.stderr.decode("utf-8", "replace").strip()[:300]))
    return p.stdout


def _git(repo, *args):
    return _git_bytes(repo, *args).decode("utf-8", "replace")


def skill_commit_of(skill_dir=SKILL_DIR):
    """Return the last commit that touched the skill folder, or None when unknown."""
    p = subprocess.run(["git", "-C", skill_dir, "log", "-1", "--format=%H", "--", "."], capture_output=True, check=False)
    sha = p.stdout.decode().strip() if p.returncode == 0 else ""
    return sha or None


def monorepo_head(mono, require_clean=True):
    """Return the HEAD SHA of the monorepo checkout; fail if it is dirty and require_clean."""
    if not os.path.isdir(os.path.join(mono, ".git")) and not os.path.isfile(os.path.join(mono, ".git")):
        raise ExportError("--monorepo %s is not a git checkout" % mono)
    if require_clean:
        dirty = _git(mono, "status", "--porcelain", "--untracked-files=all").splitlines()
        if dirty:
            raise ExportError("the monorepo checkout %s is not clean (%d changed paths, first: %s). Export from a clean checkout of "
                              "origin/main (a fresh worktree); the HEAD commit is recorded as the source SHA." % (mono, len(dirty), dirty[0]))
    return _git(mono, "rev-parse", "HEAD").strip()


def read_source_tree(mono, sha, provider, dest):
    """Extract carved-providers.json and lib/providers/<provider> at sha into dest (git archive, local only)."""
    paths = [CARVED_FILE, "lib/providers/" + provider]
    chk = subprocess.run(["git", "-C", mono, "cat-file", "-e", sha + "^{commit}"], capture_output=True, check=False)
    if chk.returncode != 0:
        raise ExportError("commit %s is not in the monorepo checkout %s. Fetch it there first (git -C %s fetch origin); this script never uses the network."
                          % (sha, mono, mono))
    data = _git_bytes(mono, "archive", "--format=tar", sha, *paths)
    with tarfile.open(fileobj=io.BytesIO(data)) as tf:
        for m in tf.getmembers():
            if m.issym() or m.islnk():
                raise ExportError("%s is a link in the monorepo: links are not supported in an export" % m.name)
        try:
            tf.extractall(dest, filter="data")
        except TypeError:  # Python < 3.12 has no extraction filters; names come from git, links are refused above
            tf.extractall(dest)


def load_entry(src, provider):
    """Return the mirror entry of provider from carved-providers.json under src or raise ExportError."""
    path = os.path.join(src, CARVED_FILE)
    if not os.path.isfile(path):
        raise ExportError("%s does not exist at the source commit: the provider must be listed there with mode \"mirror\" "
                          "by the identity-switch PR in the monorepo" % CARVED_FILE)
    try:
        with open(path, encoding="utf-8") as f:
            entries = json.load(f)
    except ValueError as e:
        raise ExportError("%s is not valid JSON: %s" % (CARVED_FILE, e))
    for e in entries if isinstance(entries, list) else []:
        if isinstance(e, dict) and e.get("name") == provider:
            if e.get("mode") != "mirror":
                raise ExportError("%s lists %s with mode %r, only \"mirror\" can be exported" % (CARVED_FILE, provider, e.get("mode")))
            n = names.derive(provider)
            if e.get("repo") != n["repo"] or e.get("goModule") != n["go_module"]:
                raise ExportError("%s entry for %s has repo %r / goModule %r, want %r / %r"
                                  % (CARVED_FILE, provider, e.get("repo"), e.get("goModule"), n["repo"], n["go_module"]))
            return e
    raise ExportError("%s does not list provider %r. Add its entry (mode \"mirror\") in the monorepo identity-switch PR first."
                      % (CARVED_FILE, provider))


def _walk(root):
    out = {}
    for dp, dns, fns in os.walk(root):
        dns.sort()
        for fn in sorted(fns):
            full = os.path.join(dp, fn)
            rel = os.path.relpath(full, root).replace(os.sep, "/")
            with open(full, "rb") as f:
                out[rel] = (f.read(), bool(os.stat(full).st_mode & 0o111))
    return out


def rewrite_go(data, provider):
    """Rewrite monorepo import paths of the provider module to the pulumi-labs module path."""
    old = ("github.com/pulumi/autoregistry/lib/providers/%s/provider/" % provider).encode()
    new = ("github.com/pulumi-labs/pulumi-%s/provider/" % provider).encode()
    return data.replace(old, new)


def rewrite_gomod(text, provider, new_module, bridged=False):
    """Return go.mod text with only the module line replaced; fail if it is not the monorepo module.

    A bridged provider's monorepo module is the vanity path github.com/pulumi/pulumi-<p>/provider (or already the
    pulumi-labs one when the identity-switch PR renamed it).
    """
    old_module = ("github.com/pulumi/pulumi-%s/provider" % provider if bridged
                  else "github.com/pulumi/autoregistry/lib/providers/%s/provider" % provider)
    accepted = {old_module, new_module} if bridged else {old_module}
    lines = text.split("\n")
    for i, line in enumerate(lines):
        m = re.match(r"^(\s*module\s+)(\S+)(\s*(//.*)?)$", line)
        if m:
            if m.group(2).strip('"') not in accepted:
                raise ExportError("provider/go.mod declares module %s, want %s" % (m.group(2), " or ".join(sorted(accepted))))
            lines[i] = m.group(1) + new_module + (m.group(3) or "")
            return "\n".join(lines)
    raise ExportError("provider/go.mod has no module line")


