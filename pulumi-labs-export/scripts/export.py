#!/usr/bin/env python3
"""Deterministic export of a mirrored monorepo provider into its pulumi-labs repo.

The monorepo provider (lib/providers/<p>/ in pulumi/autoregistry) is the source
of truth. The pulumi-labs repo is a generated mirror: this script OVERWRITES it
with a fresh export. Same monorepo commit plus same skill version gives
byte-identical output, except schema.json and sdk/, which `make` produces.

    python3 scripts/export.py --monorepo ../autoregistry --provider modal --out ../pulumi-modal
    python3 scripts/export.py --monorepo ../autoregistry --provider modal --out . --generate

Preconditions (each fails with an exact message): the provider is listed in
carved-providers.json with mode "mirror"; the monorepo checkout is clean (its
HEAD is the recorded source SHA); provider/go.mod has no relative replace;
docs/_index.md and docs/installation-configuration.md exist; the monorepo copy
already carries the pulumi-labs identity (switched in the identity-switch PR).

Two archetypes (references/bridged.md). A provider with provider/cmd/pulumi-tfgen-<p>
is a Terraform-bridged one and is exported with the "bridged" archetype: the Go
module stays in provider/, its relative replace to the in-repo shim module is kept
(it must resolve inside the exported tree), version.txt is required, and the cmd/
mains are rendered from archetype-bridged/. Everything else is "native" and behaves
exactly as described above.

The monorepo content is read from the git object database at the source SHA,
never from the working tree. The script never touches the network and never
calls gh. --generate runs `make schema` and `make sdks` in --out, which do
download Go modules; that is the only network use.
"""
