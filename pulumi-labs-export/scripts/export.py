#!/usr/bin/env python3
"""Deterministic export of a mirrored monorepo provider into its pulumi-labs repo.

The monorepo provider (lib/providers/<p>/ in pulumi/autoregistry) is the source
of truth. The pulumi-labs repo is a generated mirror: this script OVERWRITES it
with a fresh export. Same monorepo commit plus same skill version gives
byte-identical output, except schema.json and sdk/, which `make` produces.

    python3 scripts/export.py --monorepo ../autoregistry --provider modal --out ../pulumi-modal
    python3 scripts/export.py --monorepo ../autoregistry --provider modal --out . --generate

Preconditions (each fails with an exact message): the provider is listed in
carved-providers.json with mode "mirror"; the monorepo checkout is clean (its
HEAD is the recorded source SHA); provider/go.mod has no relative replace;
docs/_index.md and docs/installation-configuration.md exist; the monorepo copy
already carries the pulumi-labs identity (switched in the identity-switch PR).

The monorepo content is read from the git object database at the source SHA,
never from the working tree. The script never touches the network and never
calls gh. --generate runs `make schema` and `make sdks` in --out, which do
download Go modules; that is the only network use.
"""
import argparse
import io
import json
import os
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bootstrap  # noqa: E402
import check  # noqa: E402
import gomod  # noqa: E402
import names  # noqa: E402
import render  # noqa: E402

SKILL_DIR = render.SKILL_DIR
SOURCE_REPO = "pulumi/autoregistry"
CARVED_FILE = "carved-providers.json"
# Top-level monorepo provider paths that are copied; nothing else is. This is
# why version.txt, the monorepo Makefile, provider/go.mod and skills/ never
# reach the mirror (go.mod/go.sum are moved to the root explicitly).
COPY_TREES = [("provider/cmd", "provider/cmd"), ("provider/pkg", "provider/pkg"),
              ("examples", "examples"), ("templates", "templates"), ("docs", "docs")]
COPY_FILES = ["README.md", "CHANGELOG.md"]
REQUIRED_DOCS = ["docs/_index.md", "docs/installation-configuration.md"]
VERSION_RE = re.compile(r"^0\.\d+\.\d+$")
MAX_HITS = 40
CLAUDE_HEADER = ("<!-- Generated by pulumi-labs-export from the provider's skills/SKILLS.md at the source commit "
                 "recorded in .pulumi-labs-export.json. This repo is a generated mirror: do not edit this file, "
                 "fix the source and re-sync. -->\n\n")
MIRROR_META = (  # (regex that must NOT match a non-test provider .go file, what to tell the human)
    (re.compile(r'WithPublisher\(\s*"Pulumi"\s*\)'), 'WithPublisher("Pulumi") must be "Pulumi Labs"'),
    (re.compile(r'WithRepository\(\s*"https://github\.com/pulumi/'), "WithRepository must be https://github.com/pulumi-labs/pulumi-<p>"),
    (re.compile(r'WithGoImportPath\(\s*"github\.com/pulumi/'), "WithGoImportPath must start with github.com/pulumi-labs/pulumi-<p>/sdk/go/"),
)


class ExportError(Exception):
    """Raised for any condition the operator must fix; the message is actionable."""


def _git_bytes(repo, *args):
    p = subprocess.run(["git", "-C", repo] + list(args), capture_output=True, check=False)
    if p.returncode != 0:
        raise ExportError("git %s failed in %s: %s" % (" ".join(args[:2]), repo, p.stderr.decode("utf-8", "replace").strip()[:300]))
    return p.stdout


def _git(repo, *args):
    return _git_bytes(repo, *args).decode("utf-8", "replace")


def skill_commit_of(skill_dir=SKILL_DIR):
    """Return the last commit that touched the skill folder, or None when unknown."""
    p = subprocess.run(["git", "-C", skill_dir, "log", "-1", "--format=%H", "--", "."], capture_output=True, check=False)
    sha = p.stdout.decode().strip() if p.returncode == 0 else ""
    return sha or None


def monorepo_head(mono, require_clean=True):
    """Return the HEAD SHA of the monorepo checkout; fail if it is dirty and require_clean."""
    if not os.path.isdir(os.path.join(mono, ".git")) and not os.path.isfile(os.path.join(mono, ".git")):
        raise ExportError("--monorepo %s is not a git checkout" % mono)
    if require_clean:
        dirty = _git(mono, "status", "--porcelain", "--untracked-files=all").splitlines()
        if dirty:
            raise ExportError("the monorepo checkout %s is not clean (%d changed paths, first: %s). Export from a clean checkout of "
                              "origin/main (a fresh worktree); the HEAD commit is recorded as the source SHA." % (mono, len(dirty), dirty[0]))
    return _git(mono, "rev-parse", "HEAD").strip()


def read_source_tree(mono, sha, provider, dest):
    """Extract carved-providers.json and lib/providers/<provider> at sha into dest (git archive, local only)."""
    paths = [CARVED_FILE, "lib/providers/" + provider]
    chk = subprocess.run(["git", "-C", mono, "cat-file", "-e", sha + "^{commit}"], capture_output=True, check=False)
    if chk.returncode != 0:
        raise ExportError("commit %s is not in the monorepo checkout %s. Fetch it there first (git -C %s fetch origin); this script never uses the network."
                          % (sha, mono, mono))
    data = _git_bytes(mono, "archive", "--format=tar", sha, *paths)
    with tarfile.open(fileobj=io.BytesIO(data)) as tf:
        for m in tf.getmembers():
            if m.issym() or m.islnk():
                raise ExportError("%s is a link in the monorepo: links are not supported in an export" % m.name)
        try:
            tf.extractall(dest, filter="data")
        except TypeError:  # Python < 3.12 has no extraction filters; names come from git, links are refused above
            tf.extractall(dest)


def load_entry(src, provider):
    """Return the mirror entry of provider from carved-providers.json under src or raise ExportError."""
    path = os.path.join(src, CARVED_FILE)
    if not os.path.isfile(path):
        raise ExportError("%s does not exist at the source commit: the provider must be listed there with mode \"mirror\" "
                          "by the identity-switch PR in the monorepo" % CARVED_FILE)
    try:
        with open(path, encoding="utf-8") as f:
            entries = json.load(f)
    except ValueError as e:
        raise ExportError("%s is not valid JSON: %s" % (CARVED_FILE, e))
    for e in entries if isinstance(entries, list) else []:
        if isinstance(e, dict) and e.get("name") == provider:
            if e.get("mode") != "mirror":
                raise ExportError("%s lists %s with mode %r, only \"mirror\" can be exported" % (CARVED_FILE, provider, e.get("mode")))
            n = names.derive(provider)
            if e.get("repo") != n["repo"] or e.get("goModule") != n["go_module"]:
                raise ExportError("%s entry for %s has repo %r / goModule %r, want %r / %r"
                                  % (CARVED_FILE, provider, e.get("repo"), e.get("goModule"), n["repo"], n["go_module"]))
            return e
    raise ExportError("%s does not list provider %r. Add its entry (mode \"mirror\") in the monorepo identity-switch PR first."
                      % (CARVED_FILE, provider))


def _walk(root):
    out = {}
    for dp, dns, fns in os.walk(root):
        dns.sort()
        for fn in sorted(fns):
            full = os.path.join(dp, fn)
            rel = os.path.relpath(full, root).replace(os.sep, "/")
            with open(full, "rb") as f:
                out[rel] = (f.read(), bool(os.stat(full).st_mode & 0o111))
    return out


def rewrite_go(data, provider):
    """Rewrite monorepo import paths of the provider module to the pulumi-labs module path."""
    old = ("github.com/pulumi/autoregistry/lib/providers/%s/provider/" % provider).encode()
    new = ("github.com/pulumi-labs/pulumi-%s/provider/" % provider).encode()
    return data.replace(old, new)


def rewrite_gomod(text, provider, new_module):
    """Return go.mod text with only the module line replaced; fail if it is not the monorepo module."""
    old_module = "github.com/pulumi/autoregistry/lib/providers/%s/provider" % provider
    lines = text.split("\n")
    for i, line in enumerate(lines):
        m = re.match(r"^(\s*module\s+)(\S+)(\s*(//.*)?)$", line)
        if m:
            if m.group(2).strip('"') != old_module:
                raise ExportError("provider/go.mod declares module %s, want %s" % (m.group(2), old_module))
            lines[i] = m.group(1) + new_module + (m.group(3) or "")
            return "\n".join(lines)
    raise ExportError("provider/go.mod has no module line")


def _read_option_file(out):
    try:
        return render.read_options(out)
    except (OSError, ValueError):
        return None


def display_name_from_source(pdir):
    """Return the WithDisplayName value from the provider's Go sources, or None."""
    for rel, (data, _) in sorted(_walk(os.path.join(pdir, "provider", "pkg")).items()):
        if rel.endswith(".go") and not rel.endswith("_test.go"):
            m = re.search(rb'WithDisplayName\(\s*"([^"\n]+)"\s*\)', data)
            if m:
                return m.group(1).decode("utf-8")
    return None


def build_tree(src, provider, stage, *, sha, display_name, excludes, skill_commit):
    """Write the full export of the provider found under src into the empty dir stage; return the options dict.

    Pure: depends only on the arguments and the vendored archetype. No network, no clock, no environment.
    """
    n = names.derive(provider)
    pdir = os.path.join(src, "lib", "providers", provider)
    if not os.path.isdir(pdir):
        raise ExportError("lib/providers/%s does not exist at the source commit" % provider)
    load_entry(src, provider)

    gm = os.path.join(pdir, "provider", "go.mod")
    if not os.path.isfile(gm):
        raise ExportError("lib/providers/%s/provider/go.mod not found" % provider)
    with open(gm, encoding="utf-8") as f:
        gm_text = f.read()
    rel_replaces = [(o, t) for o, t in gomod.parse_gomod(gm_text)["replaces"] if t.startswith((".", "/"))]
    if rel_replaces:
        raise ExportError("provider/go.mod has relative replace directive(s) (%s). Exporting such a module is unsupported for now: "
                          "remove the replace in the monorepo (published versions only), then export again."
                          % ", ".join("%s => %s" % r for r in rel_replaces))
    missing = [d for d in REQUIRED_DOCS if not os.path.isfile(os.path.join(pdir, d))]
    if missing:
        raise ExportError("lib/providers/%s is missing %s. Add these Registry pages in the monorepo identity-switch PR "
                          "(model: the archetype's docs, see references/archetype.md and `gh api repos/pulumi-labs/pulumi-nvidia-aicr/contents/docs`); "
                          "the export never invents them." % (provider, " and ".join(missing)))
    ver_path = os.path.join(pdir, "version.txt")
    if not os.path.isfile(ver_path):
        raise ExportError("lib/providers/%s/version.txt not found" % provider)
    with open(ver_path, encoding="utf-8") as f:
        version = f.read().strip()
    if not VERSION_RE.match(version):
        raise ExportError("version.txt is %r: while experimental the version must be 0.x.y" % version)
    skills = os.path.join(pdir, "skills", "SKILLS.md")
    if not os.path.isfile(skills):
        raise ExportError("lib/providers/%s/skills/SKILLS.md not found (it becomes CLAUDE.md)" % provider)

    display = display_name or display_name_from_source(pdir)
    if not display:
        raise ExportError("no display name: pass --display-name (the provider sets none via WithDisplayName)")
    try:
        options = render.make_options(provider, display, excludes)
    except render.RenderError as e:
        raise ExportError(str(e))

    files = {}
    for srcrel, dstrel in COPY_TREES:
        base = os.path.join(pdir, srcrel)
        if os.path.isdir(base):
            for rel, val in _walk(base).items():
                files[dstrel + "/" + rel] = val
    for fn in COPY_FILES:
        p = os.path.join(pdir, fn)
        if os.path.isfile(p):
            files[fn] = _walk_one(p)
    for rel in list(files):
        if rel.endswith(".go"):
            files[rel] = (rewrite_go(files[rel][0], provider), files[rel][1])
    files["go.mod"] = (rewrite_gomod(gm_text, provider, n["go_module"]).encode("utf-8"), False)
    sum_path = os.path.join(pdir, "provider", "go.sum")
    if os.path.isfile(sum_path):
        files["go.sum"] = _walk_one(sum_path)
    with open(skills, "rb") as f:
        files["CLAUDE.md"] = (CLAUDE_HEADER.encode("utf-8") + f.read(), False)

    for rel in sorted(files):
        dest = os.path.join(stage, rel)
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with open(dest, "wb") as f:
            f.write(files[rel][0])
        os.chmod(dest, 0o755 if files[rel][1] else 0o644)

    options.update({"source_repo": SOURCE_REPO, "source_sha": sha, "source_version": version, "skill_commit": skill_commit})
    render.write_repo(stage, options)
    _normalize_modes(stage)
    problems = identity_problems(stage, provider)
    if problems:
        shown = problems[:MAX_HITS]
        raise ExportError("the monorepo copy still has pulumi/ identity values (%d). The identity must be switched to pulumi-labs IN THE MONOREPO "
                          "with one reviewed identity-switch PR before the first export (SKILL.md step b, references/export.md); never patch it in the mirror:\n%s%s"
                          % (len(problems), "\n".join("  " + p for p in shown),
                             ("\n  ... and %d more" % (len(problems) - len(shown))) if len(problems) > len(shown) else ""))
    return options


def _walk_one(path):
    with open(path, "rb") as f:
        return f.read(), bool(os.stat(path).st_mode & 0o111)


def _normalize_modes(stage):
    """Archetype files are written with the process umask; pin every mode so output is byte-for-byte reproducible."""
    for rel, (_, is_exec) in _walk(stage).items():
        os.chmod(os.path.join(stage, rel), 0o755 if is_exec else 0o644)


def identity_problems(stage, provider):
    """Return 'file:line: what' strings for pulumi/ identity values left in the staged export."""
    pats = check.namespace_patterns(provider)
    out = []
    for rel, (data, _) in sorted(_walk(stage).items()):
        if rel in ("go.sum", render.OPTIONS_FILE) or b"\0" in data[:8192]:
            continue
        is_prov_go = rel.startswith("provider/") and rel.endswith(".go") and not rel.endswith("_test.go")
        for lineno, line in enumerate(data.decode("utf-8", "replace").splitlines(), 1):
            for label, rx in pats:
                if rx.search(line):
                    out.append("%s:%d: %s: %s" % (rel, lineno, label, line.strip()[:110]))
            if is_prov_go:
                for rx, msg in MIRROR_META:
                    if rx.search(line):
                        out.append("%s:%d: %s" % (rel, lineno, msg))
    return out


def clear_dir_except_git(out):
    """Remove everything directly inside out except .git."""
    for entry in sorted(os.listdir(out)):
        if entry == ".git":
            continue
        full = os.path.join(out, entry)
        if os.path.isdir(full) and not os.path.islink(full):
            shutil.rmtree(full)
        else:
            os.remove(full)


def check_out_dir(out, mono):
    """Refuse output directories that could destroy something that is not a mirror clone."""
    real = os.path.realpath(out)
    if not os.path.isdir(out):
        raise ExportError("--out %s is not a directory (create it and `git init` or clone the mirror)" % out)
    if not os.path.exists(os.path.join(out, ".git")):
        raise ExportError("--out %s has no .git: it must be a git clone or `git init` directory, because everything but .git is removed" % out)
    mono_real = os.path.realpath(mono)
    if real == mono_real or real.startswith(mono_real + os.sep) or mono_real.startswith(real + os.sep):
        raise ExportError("--out %s overlaps the monorepo checkout %s" % (out, mono))
    if real in (os.path.realpath(os.path.expanduser("~")), os.sep):
        raise ExportError("--out %s is not acceptable" % out)


def make_env(prefix):
    """Environment for make: the bootstrapped toolchain first on PATH."""
    env = dict(os.environ)
    env["PATH"] = os.path.join(prefix, "bin") + os.pathsep + env.get("PATH", "")
    try:
        specs = bootstrap.tool_specs(bootstrap.detect_arch(), bootstrap.read_pulumi_version())
        env.update(bootstrap.toolchain_env(prefix, specs))
    except bootstrap.BootstrapError:
        pass
    env["PULUMI_SKIP_UPDATE_CHECK"] = "true"
    env["PULUMI_AUTOMATION_API_SKIP_VERSION_CHECK"] = "true"
    return env


def generate(out, version, prefix, log):
    """Run make schema and make sdks in out; raise ExportError with the log tail on failure."""
    env = make_env(prefix)
    for argv in (["make", "schema"], ["make", "sdks", "VERSION=" + version]):
        log("running %s in %s" % (" ".join(argv), out))
        p = subprocess.run(argv, cwd=out, env=env, capture_output=True, text=True, check=False)
        if p.returncode != 0:
            tail = "\n".join((p.stdout + p.stderr).strip().splitlines()[-25:])
            raise ExportError("`%s` failed (exit %d) in %s. Last output:\n%s" % (" ".join(argv), p.returncode, out, tail))


def export(mono, provider, out, *, do_generate=False, display_name=None, excludes=None, prefix=None,
           skill_commit="auto", log=None):
    """Export provider from the clean monorepo checkout mono into out (overwrite); return the options dict."""
    log = log or (lambda _msg: None)
    mono = os.path.abspath(mono)
    out = os.path.abspath(out)
    try:
        names.validate_slug(provider)
    except names.SlugError as e:
        raise ExportError(str(e))
    sha = monorepo_head(mono, require_clean=True)
    check_out_dir(out, mono)
    prev = _read_option_file(out) or {}
    if prev.get("provider") not in (None, provider):
        raise ExportError("--out records provider %r, refusing to overwrite it with %r" % (prev.get("provider"), provider))
    if display_name is None:
        display_name = prev.get("display_name")
    if not excludes:
        excludes = [(e["platform"], e["reason"]) for e in prev.get("exclude_platforms", [])]
    if skill_commit == "auto":
        skill_commit = skill_commit_of()
    work = tempfile.mkdtemp(prefix="export-")
    try:
        src = os.path.join(work, "src")
        stage = os.path.join(work, "stage")
        os.makedirs(src)
        os.makedirs(stage)
        read_source_tree(mono, sha, provider, src)
        options = build_tree(src, provider, stage, sha=sha, display_name=display_name, excludes=excludes, skill_commit=skill_commit)
        clear_dir_except_git(out)
        for rel, (data, is_exec) in sorted(_walk(stage).items()):
            dest = os.path.join(out, rel)
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            with open(dest, "wb") as f:
                f.write(data)
            os.chmod(dest, 0o755 if is_exec else 0o644)
    finally:
        shutil.rmtree(work, ignore_errors=True)
    log("exported lib/providers/%s at %s (v%s) into %s" % (provider, sha[:12], options["source_version"], out))
    if do_generate:
        generate(out, options["source_version"], os.path.abspath(prefix or bootstrap.default_prefix()), log)
    return options


def export_at_recorded_source(mono, mirror):
    """Re-run the export transform at the SHA recorded in mirror into a temp dir; return (dir, options). Caller removes dir.

    Local only: uses `git archive` of the recorded commit in the monorepo checkout.
    """
    rec = _read_option_file(mirror)
    if not rec:
        raise ExportError("%s is missing or unreadable in %s: the repo was never exported" % (render.OPTIONS_FILE, mirror))
    for key in ("provider", "source_sha", "source_repo"):
        if not rec.get(key):
            raise ExportError("%s has no %r: this repo was not produced by export.py" % (render.OPTIONS_FILE, key))
    provider, sha = rec["provider"], rec["source_sha"]
    work = tempfile.mkdtemp(prefix="drift-")
    try:
        src = os.path.join(work, "src")
        stage = os.path.join(work, "stage")
        os.makedirs(src)
        os.makedirs(stage)
        read_source_tree(os.path.abspath(mono), sha, provider, src)
        build_tree(src, provider, stage, sha=sha, display_name=rec.get("display_name"),
                   excludes=[(e["platform"], e["reason"]) for e in rec.get("exclude_platforms", [])],
                   skill_commit=rec.get("skill_commit"))
        shutil.rmtree(src)
        return stage, rec
    except BaseException:
        shutil.rmtree(work, ignore_errors=True)
        raise


def mirror_files(mirror):
    """Return {rel: (bytes, exec)} of the mirror's working files: tracked plus untracked-not-ignored, or all files outside .git."""
    p = subprocess.run(["git", "-C", mirror, "ls-files", "-co", "--exclude-standard", "-z"], capture_output=True, check=False)
    out = {}
    if p.returncode == 0:
        for rel in sorted(x for x in p.stdout.decode("utf-8", "replace").split("\0") if x):
            full = os.path.join(mirror, rel)
            if os.path.isfile(full):
                out[rel] = _walk_one(full)
        return out
    for rel, val in _walk(mirror).items():
        if not rel.startswith(".git/"):
            out[rel] = val
    return out


def drift(mirror, mono):
    """Return one string per path of mirror that differs from a fresh export at the recorded source SHA.

    sdk/ and the generated schema file are excluded: `make` produces them. Raises ExportError if the export cannot be re-run.
    """
    stage, rec = export_at_recorded_source(mono, mirror)
    try:
        want = _walk(stage)
        n = names.derive(rec["provider"])
        skip = n["schema_path"]

        def keep(rel):
            return rel != skip and not rel.startswith("sdk/")
        want = {k: v for k, v in want.items() if keep(k)}
        have = {k: v for k, v in mirror_files(mirror).items() if keep(k)}
        out = []
        for rel in sorted(set(want) | set(have)):
            if rel not in have:
                out.append("%s: missing (the export at %s has it)" % (rel, rec["source_sha"][:12]))
            elif rel not in want:
                out.append("%s: unexpected (not in the export at %s)" % (rel, rec["source_sha"][:12]))
            elif have[rel][0] != want[rel][0]:
                out.append("%s: content differs from the export at %s" % (rel, rec["source_sha"][:12]))
            elif have[rel][1] != want[rel][1]:
                out.append("%s: executable bit differs from the export at %s" % (rel, rec["source_sha"][:12]))
        return out
    finally:
        shutil.rmtree(os.path.dirname(stage), ignore_errors=True)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--monorepo", required=True, help="clean checkout of pulumi/autoregistry; its HEAD is the source SHA")
    ap.add_argument("--provider", required=True, help="provider slug, listed in carved-providers.json with mode mirror")
    ap.add_argument("--out", required=True, help="the mirror repo directory (needs .git); everything but .git is replaced")
    ap.add_argument("--generate", action="store_true", help="then run `make schema` and `make sdks VERSION=<version.txt>` in --out")
    ap.add_argument("--display-name", help="human name for CONTRIBUTING.md (default: recorded, else WithDisplayName in provider.go)")
    ap.add_argument("--exclude-platform", action="append", default=[], metavar="GOOS/GOARCH",
                    help="drop a build matrix leg (default: as recorded in --out); each needs a --reason")
    ap.add_argument("--reason", action="append", default=[], help="why the platform is excluded; pairs with --exclude-platform by order")
    ap.add_argument("--prefix", default=None, help="toolchain prefix for --generate (default: $HOME/.local/pulumi-labs-export)")
    ap.add_argument("--skill-commit", default=None, help="skill commit to record (default: last commit touching the skill folder, else null)")
    args = ap.parse_args(argv)
    if len(args.exclude_platform) != len(args.reason):
        ap.error("each --exclude-platform needs exactly one --reason")

    def log(s):
        print(s, file=sys.stderr, flush=True)
    try:
        options = export(args.monorepo, args.provider, args.out, do_generate=args.generate, display_name=args.display_name,
                         excludes=list(zip(args.exclude_platform, args.reason)), prefix=args.prefix,
                         skill_commit=args.skill_commit if args.skill_commit else "auto", log=log)
    except ExportError as e:
        print("export: error: %s" % e, file=sys.stderr)
        return 1
    print("exported %s %s@%s v%s -> %s" % (options["provider"], options["source_repo"], options["source_sha"], options["source_version"], args.out))
    print("next: python3 scripts/check.py --repo %s" % args.out)
    return 0


